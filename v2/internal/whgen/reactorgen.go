package main

import (
	"bytes"
	"fmt"

	"github.com/jimjibone/woodhouse-api/schema"
)

// baseMethods are the methods of reactors.ServiceView. Generated methods must
// not clash with them, except those in shadowOK, whose generated versions mean
// the same (the online service's own online and last_seen).
var (
	baseMethods = map[string]bool{
		"Exists": true, "Features": true, "HasFeature": true, "Attribute": true, "Has": true,
		"AttributeTime": true, "CommandSpec": true, "DeviceName": true, "Online": true, "LastSeen": true,
		"OnUpdate": true, "OnEvent": true, "Write": true, "Command": true, "Do": true, "String": true,
		"DeviceID": true, "EndpointID": true, "ServiceID": true,
	}
	shadowOK = map[string]bool{"Online": true, "LastSeen": true}
)

// reactor generates the typed reactor views of package reactors.
func reactor(s *schema.Schema) ([]byte, error) {
	var b bytes.Buffer
	t := newTypes("types.")
	collectStructs(t, s)
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("// Code generated by whgen from the woodhouse-api service schema (version %d). DO NOT EDIT.\n\n", s.Version)
	p("package reactors\n\n")
	p("import (\n\t\"context\"\n\t\"time\"\n\n\t\"github.com/jimjibone/wh/v2/types\"\n")
	p("\tclientsapi \"github.com/jimjibone/woodhouse-api/go/v2/clients\"\n\t\"github.com/jimjibone/woodhouse-api/values\"\n)\n\n")
	p("// Keep the imports used whatever the schema contains.\nvar (\n\t_ context.Context\n\t_ time.Duration\n\t_ = types.DurationOf\n\t_ *clientsapi.Value\n\t_ = values.Bool\n)\n\n")

	for _, srv := range s.Services {
		if srv.Open {
			continue // Reactor.Generic covers the generic service
		}
		reactorView(p, t, srv)
	}
	return b.Bytes(), t.err
}

func reactorView(p func(string, ...any), t *types, srv *schema.Service) {
	name := camel(srv.Name)
	view := name + "View"
	methods := map[string]bool{}
	claim := func(m string) {
		if methods[m] || (baseMethods[m] && !shadowOK[m]) {
			t.fail("%s: generated method %s clashes", view, m)
		}
		methods[m] = true
	}

	p("// %s is a reactor's view of a %s service: %s\n", view, srv.Name, srv.Desc)
	p("type %s struct{ *ServiceView }\n\n", view)
	p("// %s returns a view of the %s service on an endpoint of a device. serviceID\n// defaults to %q.\n", name, srv.Name, srv.Name)
	p("func (rc *Reactor) %s(deviceID, endpointID string, serviceID ...string) *%s {\n", name, view)
	p("\treturn &%s{rc.view(deviceID, endpointID, serviceID, %q, clientsapi.Service_%s)}\n}\n\n", view, srv.Name, srv.ProtoName())

	// Commands claim their names first; attribute getters give way.
	for _, c := range srv.Commands {
		claim(camel(c.Name))
	}

	for _, c := range srv.Commands {
		cname := camel(c.Name)
		args := "ctx context.Context"
		params := ""
		if len(c.Params) > 0 {
			args += ", p types." + paramsName(srv, c)
			params = ", p.Fields()..."
		}
		p("// %s runs the %s command and waits for it to finish.%s\n", cname, c.Name, sentence(c.Desc))
		if len(c.Result) > 0 {
			result := "types." + resultName(srv, c)
			p("func (v *%s) %s(%s) (%s, error) {\n", view, cname, args, result)
			p("\tr, err := v.Command(ctx, %q%s)\n\tif err != nil {\n\t\treturn %s{}, err\n\t}\n", c.Name, params, result)
			p("\treturn types.Parse%s(r), nil\n}\n\n", resultName(srv, c))
		} else {
			p("func (v *%s) %s(%s) error {\n\t_, err := v.Command(ctx, %q%s)\n\treturn err\n}\n\n", view, cname, args, c.Name, params)
		}
	}

	for _, e := range srv.Events {
		m := "On" + camel(e.Name)
		claim(m)
		p("// %s adds a handler for the %s event.%s Replayed events older than\n// DefaultMaxEventAge are dropped unless MaxAge says otherwise.\n", m, e.Name, sentence(e.Desc))
		if len(e.Fields) == 0 {
			p("func (v *%s) %s(handler func(info EventInfo), opts ...EventOption) {\n", view, m)
			p("\tv.OnEvent(%q, func(_ *clientsapi.Event, info EventInfo) { handler(info) }, opts...)\n}\n\n", e.Name)
		} else {
			ev := "types." + eventName(srv, e)
			p("func (v *%s) %s(handler func(e %s, info EventInfo), opts ...EventOption) {\n", view, m, ev)
			p("\tv.OnEvent(%q, func(e *clientsapi.Event, info EventInfo) { handler(types.Parse%s(e.GetFields()), info) }, opts...)\n}\n\n", e.Name, eventName(srv, e))
		}
	}

	for _, a := range srv.Attributes {
		if a.Type == schema.TypeImage {
			continue // images are fetched by the server, not mirrored
		}
		typeName := name + camel(a.Name)
		gt := t.goType(a, typeName)
		getter := camel(a.Name)
		if methods[getter] {
			if a.Type == schema.TypeBool {
				getter = "Is" + getter
			} else {
				getter += "Value"
			}
		}
		claim(getter)
		p("// %s returns %s%s, or its zero value if unknown.\n", getter, a.Name, descParen(a.Desc))
		p("func (v *%s) %s() %s {\n\treturn %s\n}\n\n", view, getter, gt, t.fromValue("v.value("+fmt.Sprintf("%q", a.Name)+")", a, typeName))

		if !a.Required {
			has := "Has" + camel(a.Name)
			claim(has)
			p("// %s reports whether %s has a value.\n", has, a.Name)
			p("func (v *%s) %s() bool {\n\treturn v.Has(%q)\n}\n\n", view, has, a.Name)
		}

		if a.Perms == schema.PermsRW {
			set := "Set" + camel(a.Name)
			claim(set)
			p("// %s writes %s and waits for the write to finish.\n", set, a.Name)
			p("func (v *%s) %s(ctx context.Context, val %s) error {\n", view, set, gt)
			p("\treturn v.Write(ctx, values.Field(%q, %s))\n}\n\n", a.Name, t.toValue("val", a, typeName))
		}
	}
}

func descParen(desc string) string {
	if desc == "" {
		return ""
	}
	return " (" + desc + ")"
}
