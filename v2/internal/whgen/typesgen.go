package main

import (
	"bytes"
	"fmt"

	"github.com/jimjibone/woodhouse-api/schema"
)

// typesFile generates package types: the struct types for list/struct
// attributes, command params and results, and event fields, with their
// conversions to and from API field values.
func typesFile(s *schema.Schema) ([]byte, error) {
	var b bytes.Buffer
	t := newTypes("")
	collectStructs(t, s)
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("// Code generated by whgen from the woodhouse-api service schema (version %d). DO NOT EDIT.\n\n", s.Version)
	p("package types\n\n")
	p("import (\n\t\"time\"\n\n")
	p("\tclientsapi \"github.com/jimjibone/woodhouse-api/go/v2/clients\"\n\t\"github.com/jimjibone/woodhouse-api/values\"\n)\n\n")
	p("// Keep the imports used whatever the schema contains.\nvar (\n\t_ time.Duration\n\t_ *clientsapi.Value\n\t_ = values.Bool\n)\n\n")
	p("// SchemaVersion is the version of the service schema this code was generated\n// from. Clients send it with every call in the SchemaVersionHeader metadata.\n")
	p("const SchemaVersion = %d\n\n", s.Version)
	p("// SchemaVersionHeader is the gRPC metadata key carrying SchemaVersion.\n")
	p("const SchemaVersionHeader = %q\n\n", schema.HeaderName)

	for _, name := range t.order {
		st := t.structs[name]
		if st.doc != "" {
			p("// %s %s\n", st.name, st.doc)
		}
		p("type %s struct {\n", st.name)
		for _, f := range st.fields {
			p("\t%s %s // %s%s\n", camel(f.Name), t.fieldType(f, st.prefix+camel(f.Name)), presence(f.Required, f.Features), descSuffix(f.Desc))
		}
		p("}\n\n")

		p("// Fields converts %s to API field values. Unset optional fields are left out.\n", st.name)
		p("func (x %s) Fields() []*clientsapi.FieldValue {\n\tvar fs []*clientsapi.FieldValue\n", st.name)
		for _, f := range st.fields {
			typeName := st.prefix + camel(f.Name)
			expr := "x." + camel(f.Name)
			switch {
			case optionalPtr(f):
				p("\tif %s != nil {\n\t\tfs = append(fs, values.Field(%q, %s))\n\t}\n", expr, f.Name, t.toValue("(*"+expr+")", f, typeName))
			case !f.Required:
				p("\tif %s != nil {\n\t\tfs = append(fs, values.Field(%q, %s))\n\t}\n", expr, f.Name, t.toValue(expr, f, typeName))
			default:
				p("\tfs = append(fs, values.Field(%q, %s))\n", f.Name, t.toValue(expr, f, typeName))
			}
		}
		p("\treturn fs\n}\n\n")

		p("// Value converts %s to an API struct value.\n", st.name)
		p("func (x %s) Value() *clientsapi.Value { return values.Struct(x.Fields()...) }\n\n", st.name)

		p("// Parse%s reads %s from API field values. Fields of the wrong kind read as\n// zero; validate against the spec first.\n", st.name, st.name)
		p("func Parse%s(fs []*clientsapi.FieldValue) %s {\n\tm := values.Fields(fs)\n\tvar x %s\n", st.name, st.name, st.name)
		for _, f := range st.fields {
			typeName := st.prefix + camel(f.Name)
			conv := t.fromValue("v", f, typeName)
			if optionalPtr(f) {
				p("\tif v, ok := m[%q]; ok {\n\t\tt := %s\n\t\tx.%s = &t\n\t}\n", f.Name, conv, camel(f.Name))
			} else {
				p("\tif v, ok := m[%q]; ok {\n\t\tx.%s = %s\n\t}\n", f.Name, camel(f.Name), conv)
			}
		}
		p("\treturn x\n}\n\n")
	}
	return b.Bytes(), t.err
}
