package main

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/jimjibone/woodhouse-api/schema"
)

var attrTypes = map[schema.Type]string{
	schema.TypeBool:     "Bool",
	schema.TypeInt:      "Int",
	schema.TypeFloat:    "Float",
	schema.TypeText:     "Text",
	schema.TypeDuration: "Duration",
	schema.TypeTime:     "Time",
	schema.TypeColor:    "Color",
	schema.TypeEnum:     "Enum",
	schema.TypeImage:    "Image",
	schema.TypeList:     "List",
	schema.TypeStruct:   "Struct",
}

// bridge generates the typed bridge-side services of package services.
func bridge(s *schema.Schema) ([]byte, error) {
	var b bytes.Buffer
	t := newTypes()
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("// Code generated by whgen from the woodhouse-api service schema (version %d). DO NOT EDIT.\n\n", s.Version)
	p("package services\n\n")
	p("import (\n\t\"time\"\n\n\t\"github.com/jimjibone/wh/v2/bridges/attributes\"\n")
	p("\tclientsapi \"github.com/jimjibone/woodhouse-api/go/v2/clients\"\n\t\"github.com/jimjibone/woodhouse-api/values\"\n)\n\n")
	p("// Keep the imports used whatever the schema contains.\nvar (\n\t_ time.Duration\n\t_ attributes.Attribute\n\t_ *clientsapi.Value\n\t_ = values.Bool\n)\n\n")

	for _, srv := range s.Services {
		if srv.Open {
			continue // the generic service is Generic itself
		}
		bridgeService(p, t, srv)
	}

	for _, name := range t.order {
		bridgeStruct(p, t, t.structs[name])
	}
	return b.Bytes(), t.err
}

func bridgeService(p func(string, ...any), t *types, srv *schema.Service) {
	name := camel(srv.Name)

	// Struct with the typed attributes.
	p("// %s: %s\n", name, srv.Desc)
	p("type %s struct {\n\t*Generic\n", name)
	for _, a := range srv.Attributes {
		p("\t%s *attributes.%s // %s%s\n", camel(a.Name), attrTypes[a.Type], presence(a.Required, a.Features), descSuffix(a.Desc))
	}
	p("}\n\n")
	p("// Static assert that %s implements the Service interface.\nvar _ Service = (*%s)(nil)\n\n", name, name)

	if len(srv.Features) > 0 {
		p("// Features of %s.\nconst (\n", name)
		for _, f := range srv.Features {
			p("\t%sFeature%s = %q // %s\n", name, camel(f.Name), f.Name, f.Desc)
		}
		p(")\n\n")
	}

	// Constructor.
	p("// New%s creates a %s service. The ID must be unique within the endpoint; \"\" means %q.\n", name, srv.Name, srv.Name)
	if len(srv.Features) > 0 {
		p("// features enables optional capabilities (%sFeature...). Attributes, commands and\n// events of features that are not enabled are absent and their fields are nil.\n", name)
		p("func New%s(id string, features ...string) *%s {\n", name, name)
		p("\tsrv := &%s{Generic: FromSchema(schemaService(%q), id, features)}\n", name, srv.Name)
	} else {
		p("func New%s(id string) *%s {\n", name, name)
		p("\tsrv := &%s{Generic: FromSchema(schemaService(%q), id, nil)}\n", name, srv.Name)
	}
	for _, a := range srv.Attributes {
		p("\tsrv.%s, _ = srv.Attribute(%q).(*attributes.%s)\n", camel(a.Name), a.Name, attrTypes[a.Type])
	}
	p("\tif s, ok := any(srv).(interface{ setup() }); ok {\n\t\ts.setup()\n\t}\n\treturn srv\n}\n\n")

	// Typed setters and getters for list and struct attributes.
	for _, a := range srv.Attributes {
		if a.Type != schema.TypeList && a.Type != schema.TypeStruct {
			continue
		}
		typeName := name + camel(a.Name)
		gt := t.goType(a, typeName)
		field := camel(a.Name)
		if a.Type == schema.TypeList {
			p("// Set%s sets %s, stamped by the server on receipt. Reports whether it changed.\n", field, a.Name)
			p("func (srv *%s) Set%s(v %s) bool {\n\treturn srv.%s.Set(%s.GetList().GetItems())\n}\n\n", name, field, gt, field, t.toValue("v", a, typeName))
			p("// %sItems returns %s.\n", field, a.Name)
			p("func (srv *%s) %sItems() %s {\n\treturn %s\n}\n\n", name, field, gt, t.fromValue("values.List(srv."+field+".Get()...)", a, typeName))
		} else {
			p("// Set%s sets %s, stamped by the server on receipt. Reports whether it changed.\n", field, a.Name)
			p("func (srv *%s) Set%s(v %s) bool {\n\treturn srv.%s.Set(v.fields())\n}\n\n", name, field, gt, field)
			p("// %sValue returns %s.\n", field, a.Name)
			p("func (srv *%s) %sValue() %s {\n\treturn parse%s(srv.%s.Get())\n}\n\n", name, field, gt, gt, field)
		}
	}

	// Commands.
	for _, c := range srv.Commands {
		cname := camel(c.Name)
		var params, result string
		if len(c.Params) > 0 {
			params = name + cname + "Params"
			t.addStruct(params, fmt.Sprintf("are the params of %s.%s.", srv.Name, c.Name), name, c.Params)
		}
		if len(c.Result) > 0 {
			result = name + cname + "Result"
			t.addStruct(result, fmt.Sprintf("is the result of %s.%s.", srv.Name, c.Name), name, c.Result)
		}
		sig := "func("
		if params != "" {
			sig += "p " + params
		}
		sig += ") "
		if result != "" {
			sig += "(" + result + ", error)"
		} else {
			sig += "error"
		}
		p("// On%s sets the handler for the %s command.%s Params arrive validated against\n// the spec.\n", cname, c.Name, sentence(c.Desc))
		if len(c.Features) > 0 {
			p("// It panics unless one of the features %s is enabled.\n", strings.Join(c.Features, ", "))
		}
		p("func (srv *%s) On%s(handler %s) {\n", name, cname, sig)
		p("\tsrv.OnCommand(%q, func(params []*clientsapi.FieldValue, _ func(*clientsapi.ActionResponse)) ([]*clientsapi.FieldValue, error) {\n", c.Name)
		call := "handler()"
		if params != "" {
			call = "handler(parse" + params + "(params))"
		}
		if result != "" {
			p("\t\tr, err := %s\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\treturn r.fields(), nil\n", call)
		} else {
			p("\t\treturn nil, %s\n", call)
		}
		p("\t})\n}\n\n")
	}

	// Events.
	for _, e := range srv.Events {
		ename := camel(e.Name)
		if len(e.Fields) == 0 {
			p("// Emit%s emits the %s event, seen now.%s\n", ename, e.Name, sentence(e.Desc))
			p("func (srv *%s) Emit%s() error {\n\treturn srv.Emit(%q)\n}\n\n", name, ename, e.Name)
			continue
		}
		ev := name + ename + "Event"
		t.addStruct(ev, fmt.Sprintf("are the fields of the %s.%s event.", srv.Name, e.Name), name, e.Fields)
		p("// Emit%s emits the %s event, seen now.%s\n", ename, e.Name, sentence(e.Desc))
		p("func (srv *%s) Emit%s(e %s) error {\n\treturn srv.Emit(%q, e.fields()...)\n}\n\n", name, ename, ev, e.Name)
	}
}

// bridgeStruct writes a struct type with its conversions to and from fields.
func bridgeStruct(p func(string, ...any), t *types, st *structType) {
	if st.doc != "" {
		p("// %s %s\n", st.name, st.doc)
	}
	p("type %s struct {\n", st.name)
	for _, f := range st.fields {
		p("\t%s %s // %s%s\n", camel(f.Name), t.fieldType(f, st.prefix+camel(f.Name)), presence(f.Required, f.Features), descSuffix(f.Desc))
	}
	p("}\n\n")

	p("func (x %s) fields() []*clientsapi.FieldValue {\n\tvar fs []*clientsapi.FieldValue\n", st.name)
	for _, f := range st.fields {
		typeName := st.prefix + camel(f.Name)
		expr := "x." + camel(f.Name)
		switch {
		case optionalPtr(f):
			p("\tif %s != nil {\n\t\tfs = append(fs, values.Field(%q, %s))\n\t}\n", expr, f.Name, t.toValue("(*"+expr+")", f, typeName))
		case !f.Required:
			p("\tif %s != nil {\n\t\tfs = append(fs, values.Field(%q, %s))\n\t}\n", expr, f.Name, t.toValue(expr, f, typeName))
		default:
			p("\tfs = append(fs, values.Field(%q, %s))\n", f.Name, t.toValue(expr, f, typeName))
		}
	}
	p("\treturn fs\n}\n\n")

	p("func (x %s) value() *clientsapi.Value { return values.Struct(x.fields()...) }\n\n", st.name)

	p("func parse%s(fs []*clientsapi.FieldValue) %s {\n\tm := values.Fields(fs)\n\tvar x %s\n", st.name, st.name, st.name)
	for _, f := range st.fields {
		typeName := st.prefix + camel(f.Name)
		conv := t.fromValue("v", f, typeName)
		if optionalPtr(f) {
			p("\tif v, ok := m[%q]; ok {\n\t\tt := %s\n\t\tx.%s = &t\n\t}\n", f.Name, conv, camel(f.Name))
		} else {
			p("\tif v, ok := m[%q]; ok {\n\t\tx.%s = %s\n\t}\n", f.Name, camel(f.Name), conv)
		}
	}
	p("\treturn x\n}\n\n")
}

func presence(required bool, features []string) string {
	switch {
	case required:
		return "required"
	case len(features) > 0:
		return "feature " + strings.Join(features, " or ")
	}
	return "optional"
}

// sentence returns desc as a following sentence (" Desc."), or "".
func sentence(desc string) string {
	if desc == "" {
		return ""
	}
	return " " + strings.TrimSuffix(desc, ".") + "."
}

func descSuffix(desc string) string {
	if desc == "" {
		return ""
	}
	return ": " + desc
}
